import { json } from "./superbase.js";

const SAFE_CODES = new Set([
  "BACKEND_NOT_CONFIGURED", "AUTH_REQUIRED", "INVALID_OR_EXPIRED_SESSION", "INVALID_SESSION",
  "BODY_TOO_LARGE", "INVALID_JSON", "INVALID_AMOUNT", "INVALID_WALLET_ID", "WALLET_NOT_FOUND",
  "WALLET_NOT_ACTIVE", "CURRENCY_MISMATCH", "SENDER_WALLET_FORBIDDEN", "SAME_WALLET_NOT_ALLOWED",
  "SELF_PAYMENT_NOT_ALLOWED", "INSUFFICIENT_FUNDS", "INSUFFICIENT_AVAILABLE_FUNDS", "NOTE_TOO_LONG",
  "IDEMPOTENCY_KEY_REQUIRED", "INVALID_IDEMPOTENCY_KEY", "IDEMPOTENCY_KEY_REUSED", "IDEMPOTENCY_IN_PROGRESS",
  "INVALID_QR_TOKEN", "INVALID_QR_OR_WALLET", "PAYMENT_REQUEST_NOT_FOUND", "PAYMENT_REQUEST_NOT_PAYABLE",
  "PAYMENT_REQUEST_EXPIRED", "MERCHANT_NOT_ACTIVE", "MERCHANT_WALLET_NOT_FOUND", "QR_AMOUNT_MISMATCH",
  "MERCHANT_FORBIDDEN", "INVALID_BUSINESS_NAME", "INVALID_BUSINESS_TYPE", "INVALID_DESTINATION_TYPE",
  "INVALID_DESTINATION_REFERENCE", "INVALID_ENCRYPTED_DESTINATION", "WITHDRAWAL_ENCRYPTION_KEY_INVALID", "WITHDRAWAL_ENCRYPTION_NOT_CONFIGURED",
  "WITHDRAWAL_NOT_FOUND", "MAKER_CANNOT_APPROVE_OWN_WITHDRAWAL", "WITHDRAWAL_NOT_REVIEWABLE",
  "INVALID_DECISION", "INVALID_WITHDRAWAL_ID", "INVALID_MERCHANT_ID", "INVALID_MERCHANT_STATUS", "MERCHANT_NOT_FOUND",
  "ADMIN_ROLE_REQUIRED", "MFA_REQUIRED", "SUPER_ADMIN_REQUIRED", "TEST_MODE_DISABLED", "TEST_CREDIT_LIMIT_EXCEEDED", "SYSTEM_WALLET_NOT_ALLOWED", "COMMENT_TOO_LONG", "DESCRIPTION_TOO_LONG", "INVALID_EXPIRY",
]);

export function financialFail(error) {
  const candidate = String(error?.message || "").match(/[A-Z][A-Z0-9_]{3,}/)?.[0] || "BACKEND_OPERATION_FAILED";
  const code = SAFE_CODES.has(candidate) ? candidate : "BACKEND_OPERATION_FAILED";
  const status = Number(error?.status) || (code === "BACKEND_NOT_CONFIGURED" ? 503 : 400);
  return json({ error: code }, status);
}
